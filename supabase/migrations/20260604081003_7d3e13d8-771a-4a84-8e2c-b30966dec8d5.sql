
-- Diagnostics
CREATE TABLE public.mentor10k_diagnostics (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  goal text NOT NULL,
  current_situation text NOT NULL,
  monthly_income_eur numeric,
  available_hours_week int,
  skills text,
  resources text,
  obstacles text,
  deadline_months int DEFAULT 3,
  profile_type text,
  raw_answers jsonb,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
GRANT SELECT, INSERT, UPDATE, DELETE ON public.mentor10k_diagnostics TO authenticated;
GRANT ALL ON public.mentor10k_diagnostics TO service_role;
ALTER TABLE public.mentor10k_diagnostics ENABLE ROW LEVEL SECURITY;
CREATE POLICY "own diagnostics select" ON public.mentor10k_diagnostics FOR SELECT TO authenticated USING (auth.uid() = user_id OR public.has_role(auth.uid(), 'admin'));
CREATE POLICY "own diagnostics insert" ON public.mentor10k_diagnostics FOR INSERT TO authenticated WITH CHECK (auth.uid() = user_id AND public.has_mentor10k_access(auth.uid()));
CREATE POLICY "own diagnostics update" ON public.mentor10k_diagnostics FOR UPDATE TO authenticated USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);
CREATE POLICY "own diagnostics delete" ON public.mentor10k_diagnostics FOR DELETE TO authenticated USING (auth.uid() = user_id);
CREATE TRIGGER trg_mentor10k_diag_upd BEFORE UPDATE ON public.mentor10k_diagnostics FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- Plans (generated by Gemini)
CREATE TABLE public.mentor10k_plans (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  diagnostic_id uuid REFERENCES public.mentor10k_diagnostics(id) ON DELETE SET NULL,
  title text NOT NULL,
  summary text,
  phases jsonb NOT NULL DEFAULT '[]'::jsonb,
  weekly_tasks jsonb NOT NULL DEFAULT '[]'::jsonb,
  kpis jsonb,
  duration_weeks int DEFAULT 12,
